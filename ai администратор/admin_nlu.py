"""
Распознавание админских команд из простого текста.

Единый реестр INTENTS — источник правды и для роутера (понять, что админ
написал «покажи дашборд за неделю» → команда dashboard, период 7), и для
генератора PDF-справочника (generate_admin_pdf.py читает тот же список).

Роутер работает ТОЛЬКО для админов (проверка в bot.py). Сопоставление —
по приоритетному списку регулярок: первая сработавшая выигрывает, поэтому
более специфичные интенты стоят выше общих.
"""
from __future__ import annotations

