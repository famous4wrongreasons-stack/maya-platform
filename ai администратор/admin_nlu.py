# Скомпилируем regex'ы один раз
for _it in INTENTS:
    _it["_re"] = re.compile(_it["pattern"], re.IGNORECASE) if _it.get("pattern") else None


def _priority(it: dict) -> int:
    """Приоритет проверки: меньше = раньше. Действия и спец-интенты — 1,
    «*_stats» и общие — 2, дашборд (самый общий «статистика») — 3."""
    k = it["key"]
    if k == "dashboard":
        return 3
    if k.endswith("_stats") or k in ("cashiers", "ai_provider", "subscriptions_stats"):
        return 2
    return 1


# Порядок матчинга — по приоритету, при равном сохраняем исходный порядок.
_MATCH_ORDER = sorted(
    [it for it in INTENTS if it.get("_re")],
    key=lambda it: _priority(it),
)


def match(text: str) -> dict | None:
    """
    Сопоставляет текст с интентом. Возвращает dict {"key", "args"} либо None.
    Перебор по приоритету: специфичные действия раньше общих статистик.
    """
    if not text or len(text) > 300:
        return None
    for it in _MATCH_ORDER:
        if it["_re"].search(text):
            args: list[str] = []
            if it.get("period"):
                days = parse_period_days(text)
                if days:
                    args = [str(days)]
            if it.get("name"):
                nm = extract_name(text)
                if nm:
                    args = [nm]
            return {"key": it["key"], "args": args}
    return None


def categories_for_pdf() -> list[str]:
    seen = []
    for it in INTENTS:
        if it["category"] not in seen:
            seen.append(it["category"])
    return seen
