# ─── Парсер периода («за неделю», «30 дней», «квартал») ──────────────────

def parse_period_days(text: str) -> int | None:
    t = (text or "").lower()
    m = re.search(r"(\d+)\s*дн", t)
    if m:
        return int(m.group(1))
    m = re.search(r"(\d+)\s*месяц", t)
    if m:
        return int(m.group(1)) * 30
    if "недел" in t:
        return 7
    if "квартал" in t:
        return 90
    if "полугод" in t:
        return 180
    if re.search(r"\bза\s+год\b|\bгод\b", t):
        return 365
    if "месяц" in t:
        return 30
    return None


# ─── Извлечение имени (для кассиров) ─────────────────────────────────────

_NAME_STOPWORDS = {
    "сделай", "сделать", "назначь", "назначить", "выдай", "дай", "поставь",
    "добавь", "убери", "сними", "снять", "удали", "разжалуй", "отмени",
    "роль", "кассира", "кассир", "кассиром", "кассиры", "право", "права",
    "мастеру", "мастера", "мастер", "пожалуйста", "его", "ему", "и", "а",
    "для", "у", "сделать", "список", "кто", "покажи", "наш", "наших",
}


def extract_name(text: str) -> str | None:
    words = re.findall(r"[А-Яа-яЁёA-Za-z]+", text or "")
    for w in reversed(words):
        if w.lower() not in _NAME_STOPWORDS and len(w) >= 2:
            return w
    return None


