"""
Слой обезличивания.

Страховка от утечки персональных данных в AI-модель: вычищает из текста
телефоны, email, явные представления по имени и адреса перед отправкой
в модель.

ВАЖНО: произвольное имя в свободном тексте этот модуль надёжно не ловит —
поэтому имя и телефон собираются отдельным детерминированным шагом на
backend и в AI не передаются вообще. redact_pii здесь — второй рубеж
защиты на случай, если ПД попадут в обычное сообщение.
"""
import re

# Телефон: необязательный код страны (+7 / 7 / 8), затем 10 цифр
# с любыми разделителями (пробел, дефис, скобки).
PHONE_RE = re.compile(
    r'(?:(?:\+?7|8)[\s\-]?)?\(?\d{3}\)?[\s\-]?\d{3}[\s\-]?\d{2}[\s\-]?\d{2}'
)
EMAIL_RE = re.compile(r'[A-Za-z0-9._%+\-]+@[A-Za-z0-9.\-]+\.[A-Za-z]{2,}')

# Явное представление по имени: «меня зовут Иван», «моё имя — Пётр».
NAME_INTRO_RE = re.compile(
    r'((?:меня зовут|зовут меня|мо[её] имя)[\s:—-]+)'
    r'([^\s,.;!?]+(?:\s+[^\s,.;!?]+)?)',
    re.IGNORECASE,
)

# Адрес с типовым префиксом улицы: «ул. Лермонтова, 343», «проспект Кулакова 25».
ADDR_RE = re.compile(
    r'\b(?:'
    r'[Уу]л(?:иц\w*|\.)?|'
    r'[Пп]росп(?:ект\w*|\.)?|[Пп]р-т|[Пп]р\.|'
    r'[Пп]ер(?:еул\w*|\.)?|'
    r'[Шш](?:оссе\w*|\.)|'
    r'[Бб]ульвар\w*|[Бб]-р|'
    r'[Нн]аб(?:ережн\w*|\.)?|'
    r'[Пп]л(?:ощад\w*|\.)?|'
    r'[Пп]ос(?:[её]л\w*|\.)?|'
    r'[Мм]кр(?:н\.?|\.)|[Мм]икрорайон\w*'
    r')\s+'
    r'[А-ЯЁ][А-ЯЁа-яё\-]{2,}'
    r'(?:\s+[А-ЯЁ][А-ЯЁа-яё\-]{2,})?'
    r'(?:[,.]?\s*(?:д(?:ом|\.)?\s*)?\d+[а-я]?'
    r'(?:[\s/\-]\d+[а-я]?)?'
    r'(?:[,.]?\s*кв\.?\s*\d+)?)?'
)

# «от/с/из + Название + дом» — адрес без префикса улицы («от Доваторцев 75»).
ADDR_HINT_RE = re.compile(
    r'\b([Оо]т|[Дд]о|[Сс]о?|[Ии]з|[Оо]коло|[Вв]озле|[Рр]ядом\s+с)\s+'
    r'[А-ЯЁ][а-яё]{2,}(?:[\s\-][А-ЯЁ][а-яё]+)?'
    r'\s*,?\s*\d{1,4}[а-я]?(?:[\s/\-]\d{1,4}[а-я]?)?'
)

# Голый «Название улицы + номер дома» без префикса и предлога: «Доваторцев 75».
# Требуем типичное для улиц/фамилий окончание и обязательный номер,
# чтобы не путать с именами в обычном контексте.
_STREET_SUFFIX = r'(?:ова|ева|ина|цев|цева|ского|ская|ской|ная|ной|ный|ого|ая|ое|ый)'
ADDR_BARE_RE = re.compile(
    r'\b[А-ЯЁ][а-яё]+' + _STREET_SUFFIX + r'\b'
    r'(?:\s+[А-ЯЁ][а-яё]+' + _STREET_SUFFIX + r'\b)?'
    r'\s*,?\s*\d{1,4}[а-я]?(?:[\s/\-]\d{1,4}[а-я]?)?'
)


# ── Документы, карты, идентификаторы (152-ФЗ) ───────────────────────────
# Банковская карта: 13–19 цифр, возможны пробелы/дефисы между ними. Валидность
# подтверждаем алгоритмом Луна, чтобы не глотать случайные длинные числа.
CARD_RE = re.compile(r'\b\d(?:[ \-]?\d){12,18}\b')

# СНИЛС в каноничном виде XXX-XXX-XXX YY (или с дефисом перед двумя последними).
SNILS_RE = re.compile(r'\b\d{3}-\d{3}-\d{3}[ \-]\d{2}\b')

# ИНН: по ключевому слову (10/12 цифр) и «голый» 12-значный (личный ИНН —
# длина уникальна: телефон ≤ 11 цифр, карта ≥ 13).
INN_KW_RE = re.compile(r'(\bИНН\D{0,6})(\d{10,12})\b', re.IGNORECASE)
INN_BARE_RE = re.compile(r'(?<!\d)\d{12}(?!\d)')

# Паспорт РФ по ключевому слову: серия(4)+номер(6), допускается пробел.
PASSPORT_KW_RE = re.compile(r'(\bпаспорт\w*\D{0,12})(\d{4}\s?\d{6})\b', re.IGNORECASE)

# @ник (Telegram/соцсети). Email уже вырезан раньше — его «@» сюда не попадёт.
NICK_RE = re.compile(r'(?<![\w@./])@[A-Za-z0-9_]{3,}')


def _luhn_ok(num: str) -> bool:
    """Проверка номера по алгоритму Луна (валидность банковской карты)."""
    if not (13 <= len(num) <= 19) or not num.isdigit():
        return False
    total = 0
    parity = len(num) % 2
    for i, ch in enumerate(num):
        d = int(ch)
        if i % 2 == parity:
            d *= 2
            if d > 9:
                d -= 9
        total += d
    return total % 10 == 0


def _card_sub(m) -> str:
    raw = re.sub(r'\D', '', m.group(0))
    return "[КАРТА]" if _luhn_ok(raw) else m.group(0)


def redact_pii(text: str) -> str:
    """
    Заменяет на токены: email, банковские карты (с проверкой Луна), СНИЛС, ИНН,
    паспорт, телефоны, @ники, явные имена и адреса.
    Применять к тексту перед любой отправкой в AI-модель.

    ВАЖНО: произвольное ФИО в свободном тексте надёжно не ловится (см. оговорку
    в начале модуля) — основная защита в том, что имя/телефон собираются отдельным
    детерминированным шагом и в AI не уходят вовсе. Здесь — второй рубеж.
    """
    if not text:
        return text
    text = EMAIL_RE.sub("[EMAIL]", text)
    text = CARD_RE.sub(_card_sub, text)               # до телефона: карта ≥ 13 цифр
    text = SNILS_RE.sub("[СНИЛС]", text)
    text = INN_KW_RE.sub(lambda m: m.group(1) + "[ИНН]", text)
    text = PASSPORT_KW_RE.sub(lambda m: m.group(1) + "[ПАСПОРТ]", text)
    text = INN_BARE_RE.sub("[ИНН]", text)             # после карты/паспорта
    text = PHONE_RE.sub("[ТЕЛЕФОН]", text)
    text = NICK_RE.sub("[НИК]", text)
    text = NAME_INTRO_RE.sub(lambda m: m.group(1) + "[ИМЯ]", text)
    text = ADDR_RE.sub("[АДРЕС]", text)
    text = ADDR_HINT_RE.sub(lambda m: m.group(1) + " [АДРЕС]", text)
    text = ADDR_BARE_RE.sub("[АДРЕС]", text)
    return text


def contains_phone(text: str) -> bool:
    """True, если в тексте есть похожее на телефон число."""
    return bool(PHONE_RE.search(text or ""))


def is_valid_phone(text: str) -> bool:
    """
    Проверяет, что текст — корректный российский номер телефона.
    Используется при детерминированном сборе телефона на backend.
    """
    digits = re.sub(r"\D", "", text or "")
    if len(digits) == 11 and digits[0] in "78":
        return True
    if len(digits) == 10 and digits[0] == "9":
        return True
    return False
