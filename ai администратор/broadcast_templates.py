# ─── Утилиты доступа ──────────────────────────────────────────────────────

def get_by_code(code: str) -> dict | None:
    for t in TEMPLATES:
        if t["code"] == code:
            return t
    return None


def get_by_category(category_code: str) -> list[dict]:
    return [t for t in TEMPLATES if t["category"] == category_code]


def render(body: str, *, client_name: str | None = None) -> str:
    """Подставляет плейсхолдеры в текст шаблона.

    Поддерживает {name} → имя клиента (первое слово) или «друг».
    {master_first} оставляет как есть, если данных нет — admin
    при предпросмотре сам отредактирует.
    """
    if not body:
        return body
    name_short = "друг"
    if client_name:
        first = client_name.strip().split()
        if first:
            name_short = first[0]
    return body.replace("{name}", name_short)


def category_label(category_code: str) -> str:
    for code, label in CATEGORIES:
        if code == category_code:
            return label
    return category_code
