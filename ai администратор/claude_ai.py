def _msgs_with_cache(messages: list) -> list:
    """
    Возвращает messages с cache_control на последнем блоке последнего сообщения.
    Это кеш-точка для истории переписки — Anthropic запоминает префикс до этой
    точки. Внутри цикла tool-use и между запросами кеш переиспользуется и input
    до точки считается как 10% от обычной цены. Оригинальный список не меняется.
    Все строковые content оборачиваются в text-блоки ради единого формата —
    иначе кеш-ключ между вызовами не совпадает.
    """
    if not messages:
        return messages
    result = []
    last_idx = len(messages) - 1
    for i, msg in enumerate(messages):
        is_last = i == last_idx
        content = msg.get("content")
        if isinstance(content, str):
            block = {"type": "text", "text": content}
            if is_last:
                block["cache_control"] = {"type": "ephemeral"}
            result.append({**msg, "content": [block]})
        elif is_last and isinstance(content, list) and content:
            *head, last_block = content
            if isinstance(last_block, dict):
                last_block = {**last_block, "cache_control": {"type": "ephemeral"}}
            result.append({**msg, "content": [*head, last_block]})
        else:
            result.append(msg)
    return result


def _strip_anthropic_meta(value):
    """Remove Anthropic-only cache_control markers before sending data to OpenAI."""
    if isinstance(value, dict):
        return {
            k: _strip_anthropic_meta(v)
            for k, v in value.items()
            if k != "cache_control"
        }
    if isinstance(value, list):
        return [_strip_anthropic_meta(v) for v in value]
    return value


def _system_text(system_blocks: list) -> str:
    parts = []
    for block in system_blocks or []:
        if isinstance(block, dict) and block.get("type") == "text":
            parts.append(str(block.get("text") or ""))
        elif isinstance(block, str):
            parts.append(block)
    return "\n\n".join(p for p in parts if p)


def _content_text(content) -> str:
    if content is None:
        return ""
    if isinstance(content, str):
        return content
    if isinstance(content, list):
        parts = []
        for block in content:
            if isinstance(block, dict):
                if block.get("type") == "text":
                    parts.append(str(block.get("text") or ""))
                elif block.get("type") == "tool_result":
                    parts.append(str(block.get("content") or ""))
            elif hasattr(block, "type") and getattr(block, "type", None) == "text":
                parts.append(str(getattr(block, "text", "") or ""))
        return "\n".join(p for p in parts if p)
    return str(content)


def _tools_for_openai(
    role: str,
    disabled_tools: set[str] | None = None,
    mode: str | None = None,
) -> list[dict]:
    disabled = _effective_disabled_tools(disabled_tools, mode)
    tools = []
    for t in _tools_for_context(role, mode):
        if t.get("name") in disabled:
            continue
        schema = _strip_anthropic_meta(t.get("input_schema") or {
            "type": "object",
            "properties": {},
        })
        tools.append({
            "type": "function",
            "function": {
                "name": t["name"],
                "description": t.get("description", ""),
                "parameters": schema,
            },
        })
    return tools


