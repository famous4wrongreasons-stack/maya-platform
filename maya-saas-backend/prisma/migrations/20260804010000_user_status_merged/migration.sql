-- Терминальный статус для погашенного дубля аккаунта.
--
-- Отдельной миграцией сознательно: PostgreSQL не даёт использовать значение
-- enum в той же транзакции, в которой оно добавлено. Модель UserMerge и весь
-- код, который на 'merged' ссылается, приезжают следующей миграцией.
--
-- 'suspended' для этой роли не годится: он неотличим от блокировки за
-- нарушение и обратим — updateCrmTeamAccess при совпадении контакта ставит
-- status='active', а reconcileCrmTeamAccess возвращает membership в 'active'.
-- Воскрешённый пустой дубль снова начал бы участвовать в поиске личности.
ALTER TYPE "UserStatus" ADD VALUE IF NOT EXISTS 'merged';
