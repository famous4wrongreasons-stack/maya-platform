-- Cycle 03 B3.4 — устойчивая аренда сверки.
--
-- 🔴 Миграция ТОЛЬКО добавляет: две колонки и один индекс на уже существующей
-- модели. Ни новой таблицы, ни системы задач — инвариант нужен ровно один:
-- один арендатор + провайдер не сверяются двумя процессами одновременно.
--
-- Данных не трогает: существующие строки прогонов уже завершены, у них
-- `finishedAt` заполнен, и под частичный индекс они не попадают.

-- 1. Аренда.
ALTER TABLE "ReconciliationRun" ADD COLUMN "leaseUntil" TIMESTAMP(3);
ALTER TABLE "ReconciliationRun" ADD COLUMN "holderId" TEXT;

-- 2. 🔴 Главный инвариант: живой прогон у пары «арендатор + провайдер» может
--    быть только ОДИН.
--
--    Индекс частичный, и предикат — это и есть определение «живого»: прогон, у
--    которого ещё нет ни отметки завершения, ни кода сбоя. Как только прогон
--    закончился любым способом, строка выходит из индекса и место свободно.
--
--    Почему арбитром выбрана база, а не код. Претендентов на аренду минимум
--    два РАЗНЫХ процесса — планировщик и ручной запуск, — и договориться в
--    памяти они не могут по построению. Уникальность в базе — единственное
--    место, где такой спор разрешается однозначно.
--
--    Окно в ключ НЕ входит намеренно: два прохода по соседним окнам одного
--    арендатора иначе пошли бы параллельно и подрались за те же строки зеркала.
CREATE UNIQUE INDEX "ReconciliationRun_live_run_unique"
  ON "ReconciliationRun" ("tenantId", "provider")
  WHERE "finishedAt" IS NULL AND "failureCode" IS NULL;

-- 3. Поиск просроченной аренды — по ней прогон перехватывается без ручного
--    вмешательства.
CREATE INDEX "ReconciliationRun_leaseUntil_idx"
  ON "ReconciliationRun" ("leaseUntil")
  WHERE "finishedAt" IS NULL AND "failureCode" IS NULL;
