async function run(name, command, args, cleanup = false, allowFailure = false) {
  assert(!stopped || cleanup, 'Run cancelled');
  const fd = fs.openSync(path.join(output, name + '.log'), 'wx', 0o600);
  const step = { name, startedAt: new Date().toISOString() };
  receipt.steps.push(step);
  save();
  try {
    const result = await new Promise((resolve, reject) => {
      const child = spawn(
        '/usr/bin/sandbox-exec',
        ['-p', sandbox, command, ...args],
        {
          cwd: backend,
          env: environment,
          detached: true,
          stdio: ['ignore', fd, fd],
        },
      );
      active = child;
      activeCleanup = cleanup;
      let killTimer;
      const terminate = () => {
        try {
          process.kill(-child.pid, 'SIGTERM');
        } catch {}
        killTimer ??= setTimeout(() => {
          try {
            process.kill(-child.pid, 'SIGKILL');
          } catch {}
        }, 5000);
      };
      const onCancel = () => {
        if (!cleanup) terminate();
      };
      process.on('SIGTERM', onCancel);
      process.on('SIGINT', onCancel);
      const timer = setTimeout(terminate, cleanup ? 45000 : 240000);
      const done = () => {
        clearTimeout(timer);
        clearTimeout(killTimer);
        process.off('SIGTERM', onCancel);
        process.off('SIGINT', onCancel);
        active = null;
      };
      child.once('error', (error) => {
        done();
        reject(error);
      });
      child.once('close', (code, signal) => {
        done();
        resolve({ exitCode: code, signal });
      });
    });
    Object.assign(step, result);
    assert(!stopped || cleanup, 'Run cancelled');
    assert.equal(result.signal, null, 'Stage terminated');
    if (!allowFailure)
      assert.equal(result.exitCode, 0, name + ' failed; inspect local log');
    return result;
  } finally {
    fs.closeSync(fd);
    step.finishedAt = new Date().toISOString();
    save();
  }
}
