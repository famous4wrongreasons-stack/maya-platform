import { ReportingPeriodResolver } from './reporting-period.resolver';

/**
 * 🔴 Cycle 04 closure B1/B2. Календарь бизнеса и календарная личность периода.
 *
 * Оба дефекта были доказаны исполнением: «за 20 августа» в 01:30 по Москве
 * возвращало 20 ИЮЛЯ, а «с 1 по 31 августа» — один день 31 июля вместо месяца.
 * Причина одна: наступление дня решал UTC, а откат «день ещё не наступил»
 * применялся даже там, где месяц назван словом.
 */

const day = (text: string, iso: string, timezone: string) =>
  ReportingPeriodResolver.resolve(text, '', new Date(iso), timezone).args;

describe('B1 — календарь бизнеса решает, наступил ли день', () => {
  /**
   * Один и тот же местный день бизнеса обязан давать один и тот же период
   * независимо от того, какая в этот момент дата в UTC.
   */
  const MATRIX = [
    {
      note: 'Москва 00:01',
      iso: '2026-08-19T21:01:00.000Z',
      tz: 'Europe/Moscow',
    },
    {
      note: 'Москва 02:59',
      iso: '2026-08-19T23:59:00.000Z',
      tz: 'Europe/Moscow',
    },
    {
      note: 'Москва 03:01',
      iso: '2026-08-20T00:01:00.000Z',
      tz: 'Europe/Moscow',
    },
    {
      note: 'Владивосток 00:01',
      iso: '2026-08-19T14:01:00.000Z',
      tz: 'Asia/Vladivostok',
    },
    {
      note: 'Нью-Йорк 23:30 (отрицательное смещение)',
      iso: '2026-08-21T03:30:00.000Z',
      tz: 'America/New_York',
    },
    { note: 'UTC полдень', iso: '2026-08-20T12:00:00.000Z', tz: 'UTC' },
  ];

  it.each(MATRIX)('«за 20 августа» — это 20 августа: $note', ({ iso, tz }) => {
    expect(day('сколько заработали за 20 августа', iso, tz)).toEqual({
      period: 'named_day',
      day: '2026-08-20',
    });
  });

  it('боевой пример: 20 августа в 01:30 по Москве — не 20 июля', () => {
    // Этот случай был воспроизведён на HEAD до правки и вернул 2026-07-20.
    expect(
      day('за 20 августа', '2026-08-19T22:30:00.000Z', 'Europe/Moscow'),
    ).toEqual({
      period: 'named_day',
      day: '2026-08-20',
    });
  });

  it('граница месяца: 31 июля в 00:30 по Москве 1 августа', () => {
    expect(
      day('за 31 июля', '2026-07-31T21:30:00.000Z', 'Europe/Moscow'),
    ).toEqual({
      period: 'named_day',
      day: '2026-07-31',
    });
  });

  it('граница года: 1 января в 00:30 по Москве — не прошлый год', () => {
    // 2025-12-31T21:30Z — это уже 1 января 2026 в Москве.
    expect(
      day('за 1 января', '2025-12-31T21:30:00.000Z', 'Europe/Moscow'),
    ).toEqual({
      period: 'named_day',
      day: '2026-01-01',
    });
  });

  it('голое число берёт день ТЕКУЩЕГО месяца бизнеса — поведение не менялось', () => {
    // «а за 20» без месяца: месяц и год подставляются от делового сегодня, и
    // откат в прошлый месяц к этому пути не применялся никогда — он был
    // только у явно названного месяца, где как раз и врал.
    expect(day('а за 20', '2026-08-25T09:00:00.000Z', 'Europe/Moscow')).toEqual(
      {
        period: 'named_day',
        day: '2026-08-20',
      },
    );
    // 🔴 Проверка именно пояса: в 00:30 первого сентября по Москве текущий
    // месяц бизнеса — сентябрь, а по UTC — ещё август.
    expect(day('а за 20', '2026-08-31T21:30:00.000Z', 'Europe/Moscow')).toEqual(
      {
        period: 'named_day',
        day: '2026-09-20',
      },
    );
  });
});

describe('B2 — явно названный период сохраняет календарную личность', () => {
  const NOON_MSK = '2026-08-20T09:00:00.000Z';

  it('боевой пример: «с 1 по 31 августа» — это август целиком', () => {
    expect(
      day('покажи выручку с 1 по 31 августа', NOON_MSK, 'Europe/Moscow'),
    ).toEqual({
      period: 'named_range',
      from_day: '2026-08-01',
      to_day: '2026-08-31',
    });
  });

  it('«с 1 по 30 сентября» не уезжает в прошлый месяц', () => {
    expect(day('с 1 по 30 сентября', NOON_MSK, 'Europe/Moscow')).toEqual({
      period: 'named_range',
      from_day: '2025-09-01',
      to_day: '2025-09-30',
    });
  });

  it('диапазон внутри прошлого месяца остаётся в прошлом месяце', () => {
    expect(day('с 1 по 15 июля', NOON_MSK, 'Europe/Moscow')).toEqual({
      period: 'named_range',
      from_day: '2026-07-01',
      to_day: '2026-07-15',
    });
  });

  it('диапазон текущего месяца, обе границы уже прошли', () => {
    expect(day('с 1 по 10 августа', NOON_MSK, 'Europe/Moscow')).toEqual({
      period: 'named_range',
      from_day: '2026-08-01',
      to_day: '2026-08-10',
    });
  });

  it('явно названный будущий период не превращается в прошлый', () => {
    // 🔴 Пользователь назвал 2027 год словами. Подменить его прошлым только
    // потому, что он не наступил, значит ответить про другой период.
    expect(day('с 1 по 31 августа 2027', NOON_MSK, 'Europe/Moscow')).toEqual({
      period: 'named_range',
      from_day: '2027-08-01',
      to_day: '2027-08-31',
    });
    expect(day('за 25 декабря 2027', NOON_MSK, 'Europe/Moscow')).toEqual({
      period: 'named_day',
      day: '2027-12-25',
    });
  });

  it('границы упорядочены, а невозможная дата не выдумывается', () => {
    const range = day('с 1 по 31 августа', NOON_MSK, 'Europe/Moscow') as {
      from_day: string;
      to_day: string;
    };
    expect(range.from_day <= range.to_day).toBe(true);
    // 31 сентября не существует — резолвер не должен молча сдвигать дату.
    const impossible = day('с 1 по 31 сентября', NOON_MSK, 'Europe/Moscow');
    expect(impossible).not.toMatchObject({ to_day: '2025-10-01' });
  });

  it('пояс с переходом на летнее время считает свой день сам', () => {
    // Берлин: 2026-03-29 — переход на летнее время. 00:30 местного 29 марта.
    expect(
      day('за 29 марта', '2026-03-28T23:30:00.000Z', 'Europe/Berlin'),
    ).toEqual({
      period: 'named_day',
      day: '2026-03-29',
    });
  });
});
