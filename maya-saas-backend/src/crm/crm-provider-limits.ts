/**
 * Ограничения API внешних CRM — правила чужих систем, а не правила Maya.
 *
 * 🔴 Зачем это понадобилось. Ограничение «журнал отдаётся кусками не длиннее
 * 31 дня» — это лимит API YCLIENTS. До P3 он был вписан числом `31` сразу в
 * четырёх местах, три из которых лежат ЗА границей CRM: чанкование журнала и
 * окно расчёта зарплаты в аналитике и разбиение периода в AI-слое. Рядом с
 * каждым стоял комментарий, прямо называющий провайдера, — то есть модули,
 * которые о провайдере знать не должны, строили вокруг его лимита свою логику.
 *
 * Здесь у правила появляется единственный владелец. Значение не меняется:
 * поведение остаётся тем же, уходит только размазанное знание.
 *
 * Оговорка честности: это ещё не полная изоляция. По-настоящему правильно,
 * чтобы куски резала сама граница CRM, а потребитель просто просил период. Тот
 * шаг меняет место пагинации и обработку ошибок, поэтому в P3 не делается —
 * он записан отдельным пунктом.
 */

/** Максимальная длина одного запроса журнала, дни. Лимит API YCLIENTS. */
export const CRM_JOURNAL_MAX_WINDOW_DAYS = 31;

export const CRM_JOURNAL_MAX_WINDOW_MS =
  CRM_JOURNAL_MAX_WINDOW_DAYS * 24 * 60 * 60 * 1000;

/**
 * Максимальный период расчёта зарплаты, дни.
 *
 * Совпадает с окном журнала не случайно — это тот же лимит той же системы, —
 * но смысл разный, поэтому имя отдельное: выручка за длинный период остаётся
 * подтверждённой, а расчёт зарплаты за него CRM не отдаёт вовсе.
 */
export const CRM_PAYROLL_MAX_WINDOW_DAYS = 31;

/**
 * Окно финансовой выборки. Число то же, что у журнала, но смысл другой:
 * здесь ограничение стоит на кассовых операциях, а не на записях. Отдельное
 * имя нужно, чтобы при расхождении лимитов их можно было развести, не
 * перечитывая все места вызова.
 */
export const CRM_FINANCE_MAX_WINDOW_MS = CRM_JOURNAL_MAX_WINDOW_MS;
