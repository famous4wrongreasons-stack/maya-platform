/**
 * Основание денежного числа — на чём именно оно стоит.
 *
 * 🔴 Зачем это понадобилось. Одно и то же слово `revenue` в системе значило две
 * несовместимые вещи: в одном режиме — деньги, о которых отчиталась касса
 * провайдера, в другом — сумму ЦЕН ИЗ ЖУРНАЛА записей, то есть стоимость
 * записанного. Числа выглядели одинаково, назывались одинаково, а доказательная
 * сила у них разная. Владелец не мог отличить их на глаз.
 *
 * Основание отвечает на вопрос «чем это доказано», не меняя самого числа.
 */

export type RevenueBasis =
  /**
   * Операции, вернувшиеся из эндпоинта кассовых операций провайдера.
   *
   * 🔴 Имя выбрано намеренно осторожным. Напрашивалось `till_confirmed`, но оно
   * обещает фискальное подтверждение, которого провайдер НЕ ДАЁТ: в модели
   * транзакции YCLIENTS нет ни одного поля статуса, подтверждения или удаления
   * (`YclientsFinanceTransactionApiItem`), запрос ничего не фильтрует, а флаг
   * `verified` ставится безусловно при успешном чтении.
   *
   * Что это основание ДОКАЗЫВАЕТ: провайдер отчитался об этих операциях в своём
   * кассовом эндпоинте, и мы прочитали ответ целиком без ошибок разбора.
   *
   * Чего оно НЕ доказывает: ни чека, ни ККМ, ни кассовой смены, ни того, что
   * операция не была впоследствии отменена. Фискального контура у интеграции
   * нет вовсе.
   *
   * Сумма ВАЛОВАЯ: отрицательные и нулевые операции отброшены (см. §D плана),
   * поэтому возвраты в ней не учтены.
   */
  | 'provider_transactions'
  /**
   * Сумма цен из журнала записей. **Это не деньги.**
   *
   * Столько стоило записанное, а не столько пробито. Запись может быть отменена,
   * клиент может не прийти, цена может измениться при расчёте. Основание
   * существует потому, что при внутреннем календаре другого источника нет
   * в принципе — но называть это выручкой без оговорки нельзя.
   */
  | 'booked_prices'
  /** Неизвестно. Рядом обязана стоять причина. */
  | 'unavailable';

export const REVENUE_BASIS_VALUES: readonly RevenueBasis[] = [
  'provider_transactions',
  'booked_prices',
  'unavailable',
];

/**
 * Можно ли называть число этого основания подтверждённым.
 *
 * 🔴 Единственный владелец ответа на вопрос «это verified?». До P4 на него
 * отвечали в трёх местах по-разному, и AI-инструмент называл цены журнала
 * проверенными наравне с кассой.
 */
export function isEvidencedBasis(basis: RevenueBasis): boolean {
  return basis === 'provider_transactions';
}

/** Основание источника календаря, когда касса недоступна. */
export function basisForCalendarSource(
  source: 'internal' | 'external',
): RevenueBasis {
  // У внутреннего календаря кассы нет в принципе — только цены журнала.
  // У внешнего в операционном обзоре тоже используются цены журнала: касса
  // живёт в отдельном финансовом контуре и приходит другим запросом.
  void source;
  return 'booked_prices';
}
