/**
 * Присутствие клиента на визите — канонический словарь Maya.
 *
 * 🔴 Зачем это понадобилось. До P3 присутствие ездило по всей системе числовым
 * кодом YCLIENTS `1 | -1 | 0 | 2`, и код этот не отображался НИГДЕ: адаптер →
 * `CrmService` → HTTP-контроллер → DTO с `@IsIn([1,0,-1])` → PWA, где его
 * расшифровывали вручную. Кодировка одного провайдера стала публичным
 * контрактом Maya и частью интерфейса кабинета.
 *
 * P3 разрывает эту цепочку в середине: внутри системы ездит имя исхода, а
 * число остаётся ровно на двух концах — в адаптере YCLIENTS и на проводе, где
 * его читает уже выпущенный PWA. Провод в P3 не меняется намеренно: это
 * опубликованный контракт, и его изменение — отдельная работа с фронтом.
 */

export type VisitAttendance =
  /** Ждём клиента: визит впереди, отметки ещё нет. */
  | 'awaiting'
  /** Клиент пришёл. */
  | 'arrived'
  /** Клиент не пришёл. Окно потеряно вместе с деньгами. */
  | 'no_show'
  /**
   * Клиент подтвердил, что придёт. Отдельный исход у YCLIENTS (код `2`);
   * для журнала он неотличим от ожидания, но терять его при разборе нельзя.
   */
  | 'confirmed_by_client';

export const VISIT_ATTENDANCE_VALUES: readonly VisitAttendance[] = [
  'awaiting',
  'arrived',
  'no_show',
  'confirmed_by_client',
];

export function isVisitAttendance(value: unknown): value is VisitAttendance {
  return (
    typeof value === 'string' &&
    (VISIT_ATTENDANCE_VALUES as readonly string[]).includes(value)
  );
}
