/** Existing Python anonymizer's explicit name/address/identifier exclusions,
 * expressed with Unicode word boundaries for the canonical A22 ingress. */
const KNOWN_PII = [
 /[A-Za-z0-9._%+\-]+@[A-Za-z0-9.\-]+\.[A-Za-z]{2,}/u,
 /(?:\+?\d[\s().-]*){10,}/u,
 /(?<![\p{L}\p{N}_@./])@[A-Za-z0-9_]{3,}/u,
 /(?:меня зовут|зовут меня|мо[её] имя)[\s:—-]+[^\s,.;!?]+/iu,
 /(?<![\p{L}\p{N}_])(?:[Уу]л(?:иц[\p{L}\p{N}_]*|\.)?|[Пп]росп(?:ект[\p{L}\p{N}_]*|\.)?|[Пп]р-т|[Пп]р\.|[Пп]ер(?:еул[\p{L}\p{N}_]*|\.)?|[Шш](?:оссе[\p{L}\p{N}_]*|\.)|[Бб]ульвар[\p{L}\p{N}_]*|[Бб]-р|[Нн]аб(?:ережн[\p{L}\p{N}_]*|\.)?|[Пп]л(?:ощад[\p{L}\p{N}_]*|\.)?|[Пп]ос(?:[её]л[\p{L}\p{N}_]*|\.)?|[Мм]кр(?:н\.?|\.)|[Мм]икрорайон[\p{L}\p{N}_]*)\s+[А-ЯЁ][А-ЯЁа-яё\-]{2,}/u,
 /(?<![\p{L}\p{N}_])(?:[Оо]т|[Дд]о|[Сс]о?|[Ии]з|[Оо]коло|[Вв]озле|[Рр]ядом\s+с)\s+[А-ЯЁ][а-яё]{2,}(?:[\s\-][А-ЯЁ][а-яё]+)?\s*,?\s*\d{1,4}/u,
 /(?<![\p{L}\p{N}_])[А-ЯЁ][а-яё]+(?:ова|ева|ина|цев|цева|ского|ская|ской|ная|ной|ный|ого|ая|ое|ый)(?![\p{L}\p{N}_])(?:\s+[А-ЯЁ][а-яё]+(?:ова|ева|ина|цев|цева|ского|ская|ской|ная|ной|ный|ого|ая|ое|ый)(?![\p{L}\p{N}_]))?\s*,?\s*\d{1,4}/u,
];
export function businessRuleContainsKnownPii(text:string):boolean {return KNOWN_PII.some(pattern=>pattern.test(text));}
