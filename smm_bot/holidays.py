def get_holiday_for_date(date) -> tuple | None:
    """Возвращает (название, подсказка) если день праздничный, иначе None."""
    return HOLIDAYS.get((date.month, date.day))


def get_upcoming_holidays(from_date, days_ahead: int = 14) -> list:
    """Список праздников в ближайшие N дней."""
    from datetime import timedelta
    result = []
    for offset in range(days_ahead):
        check = from_date + timedelta(days=offset)
        holiday = get_holiday_for_date(check)
        if holiday:
            result.append((check, holiday[0], holiday[1]))
    return result
